<?php

namespace Aimeos\Prisma\Providers\Text;

use Aimeos\Prisma\Contracts\Text\Stream;
use Aimeos\Prisma\Contracts\Text\Structure;
use Aimeos\Prisma\Contracts\Text\Translate;
use Aimeos\Prisma\Contracts\Text\Vectorize;
use Aimeos\Prisma\Contracts\Text\Write;
use Aimeos\Prisma\Exceptions\PrismaException;
use Aimeos\Prisma\Providers\Openrouter as Base;
use Aimeos\Prisma\Responses\TextResponse;
use Aimeos\Prisma\Responses\VectorResponse;
use Aimeos\Prisma\Schema\Schema;


/**
 * Language models hosted by fal.ai.
 *
 * fal provides the models of OpenRouter by an OpenAI compatible API, so model names
 * are OpenRouter model IDs, e.g. "anthropic/claude-sonnet-5". Translations are generated by
 * the LLM using structured output.
 */
class Fal extends Base implements Stream, Structure, Translate, Vectorize, Write
{
    // server tools of OpenRouter aren't documented for the fal API
    protected const PROVIDER_TOOL_MAP = [];

    /** Maximum characters translated by one request, so the output doesn't exceed the token limit of the LLM */
    private const BATCH_CHARS = 10000;

    /** Maximum number of batches translated at the same time */
    private const BATCH_REQUESTS = 5;

    private const MODEL = 'openai/gpt-6-luna';
    private const OPTIONS = ['temperature', 'top_p', 'frequency_penalty', 'presence_penalty', 'reasoning'];


    public function __construct( array $config )
    {
        if( !isset( $config['api_key'] ) ) {
            throw new PrismaException( 'No API key' );
        }

        // "run_url" is the host of the synchronous fal endpoints
        $host = rtrim( $this->config( $config, 'run_url', 'https://fal.run' ), '/' );
        $url = $this->config( $config, 'url', $host . '/openrouter/router/openai/v1' );

        $this->header( 'Authorization', 'Key ' . $this->config( $config, 'api_key' ) );
        $this->baseUrl( rtrim( $url, '/' ) . '/' );
    }


    public function stream( string $prompt, array $files = [], array $options = [] ) : TextResponse
    {
        $options = $this->allowed( $options, self::OPTIONS );
        $messages = $this->messages( $this->content( $prompt, $files ) );

        return $this->streamCompletions( 'chat/completions', self::MODEL, $messages, $options );
    }


    public function structure( string $prompt, Schema $schema, array $files = [], array $options = [] ) : TextResponse
    {
        $mode = $options['mode'] ?? null;
        $options = $this->allowed( $options, self::OPTIONS );

        return $this->structuredCompletions(
            'chat/completions', self::MODEL,
            $prompt, $files, $schema, $options, $mode
        );
    }


    public function translate( array $texts, string $to, ?string $from = null, ?string $context = null, array $options = [] ) : TextResponse
    {
        $translated = $usage = $meta = [];
        $used = null;

        // the system prompt, messages and tools set for the other methods would change or prevent the translations
        $plain = clone $this;
        $plain->withMessages( [] )->withSystemPrompt( null )->withTools( [] );

        foreach( array_chunk( $this->batches( array_values( $texts ) ), self::BATCH_REQUESTS ) as $batches )
        {
            // all requests are sent before receiving the answers, so the LLM translates the batches at the same time
            $responses = array_map( fn( $batch ) => $plain->translation( $batch, $to, $from, $context, $options ), $batches );

            foreach( $responses as $idx => $response )
            {
                $translated = array_merge( $translated, $this->translated( $response, count( $batches[$idx] ) ) );
                $usage = $this->total( $usage, $response->usage()->all() );
                $used = $response->usage()->used() !== null ? ( $used ?? 0 ) + $response->usage()->used() : $used;
                $meta = $response->meta()->all();
            }
        }

        return TextResponse::fromTexts( $translated )->withUsage( $used, $usage )->withMeta( $meta );
    }


    public function vectorize( array $texts, ?int $size = null, array $options = [] ) : VectorResponse
    {
        $options = $this->allowed( $options, ['encoding_format', 'user'] );

        return $this->embeddings( 'embeddings', 'openai/text-embedding-3-small', $texts, $size, $options );
    }


    public function write( string $prompt, array $files = [], array $options = [] ) : TextResponse
    {
        $options = $this->allowed( $options, self::OPTIONS );

        return $this->completions(
            'chat/completions', self::MODEL,
            $this->messages( $this->content( $prompt, $files ) ),
            $options
        );
    }


    /**
     * Splits the texts into batches whose length doesn't exceed the maximum characters per request.
     *
     * @param array<int, string> $texts Texts to translate
     * @return array<int, array<int, string>> Batches of texts, texts longer than the maximum form their own batch
     */
    private function batches( array $texts ) : array
    {
        $batches = [];
        $batch = [];
        $length = 0;

        foreach( $texts as $text )
        {
            if( !empty( $batch ) && $length + mb_strlen( $text ) > self::BATCH_CHARS )
            {
                $batches[] = $batch;
                $batch = [];
                $length = 0;
            }

            $batch[] = $text;
            $length += mb_strlen( $text );
        }

        return empty( $batch ) ? $batches : array_merge( $batches, [$batch] );
    }


    /**
     * Returns the prompt for translating the texts.
     *
     * @param array<int, string> $texts Texts to translate
     * @param string $to ISO language code to translate into
     * @param string|null $from ISO language code of the texts or NULL to detect it
     * @param string|null $context Context of the texts for better translations
     * @return string Prompt for the LLM
     */
    private function prompt( array $texts, string $to, ?string $from, ?string $context ) : string
    {
        return 'Translate each text of the JSON list ' . ( $from ? 'from the language of ISO code "' . $from . '" ' : '' )
            . 'into the language of ISO code "' . $to . '" and return the translations in the same order.'
            . ( $context ? "\nContext of the texts: " . $context : '' )
            . "\nTexts: " . json_encode( $texts, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR );
    }


    /**
     * Adds the numeric usage values of two responses.
     *
     * @param array<mixed> $usage Usage values summed up so far
     * @param array<mixed> $more Usage values of the next response
     * @return array<mixed> Summed usage values
     */
    private function total( array $usage, array $more ) : array
    {
        foreach( $more as $key => $value )
        {
            $current = $usage[$key] ?? null;

            $usage[$key] = match( true ) {
                is_array( $value ) => $this->total( is_array( $current ) ? $current : [], $value ),
                is_int( $value ) || is_float( $value ) => ( is_int( $current ) || is_float( $current ) ? $current : 0 ) + $value,
                default => $value,
            };
        }

        return $usage;
    }


    /**
     * Returns the validated translations of one batch.
     *
     * @param TextResponse $response Structured output response of the batch
     * @param int $count Number of texts in the batch
     * @return array<int, string> Translated texts in the same order
     * @throws PrismaException If the translations are invalid
     */
    private function translated( TextResponse $response, int $count ) : array
    {
        $translated = $this->parseJson( $response->text() )['texts'] ?? null;

        if( !is_array( $translated ) || !array_is_list( $translated ) || count( $translated ) !== $count
            || array_filter( $translated, 'is_string' ) !== $translated
        ) {
            throw new PrismaException( 'Invalid translations in fal response' );
        }

        return $translated;
    }


    /**
     * Sends the request translating one batch of texts using structured output.
     *
     * The request is sent immediately but the answer is received when the response is used.
     *
     * @param array<int, string> $texts Texts to translate
     * @param string $to ISO language code to translate into
     * @param string|null $from ISO language code of the texts or NULL to detect it
     * @param string|null $context Context of the texts for better translations
     * @param array<string, mixed> $options Provider specific options
     * @return TextResponse Lazy response
     */
    private function translation( array $texts, string $to, ?string $from, ?string $context, array $options ) : TextResponse
    {
        $schema = Schema::for( 'translation', [
            'texts' => Schema::array()->items( Schema::string() ),
        ] );

        [$prompt, $params] = $this->structuredRequest(
            $this->prompt( $texts, $to, $from, $context ), $schema,
            $this->allowed( $options, self::OPTIONS ), $options['mode'] ?? null
        );

        return $this->deferCompletions( 'chat/completions', self::MODEL, $this->messages( $this->content( $prompt, [] ) ), $params );
    }
}
